using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using PaymentLedger.Application.Accounts.Commands;

namespace PaymentLedger.Application.Common;

/// <summary>
/// Computes the fingerprint stored next to an idempotency key (ADR-0007): the SHA-256,
/// in lowercase hex, of a canonical, versioned text form of the fields that decide where
/// money goes and how much. Two requests that would post the same movement produce the
/// same fingerprint; anything else produces a different one.
/// </summary>
/// <remarks>
/// Included: operation, account ids, amount (normalised so 10.50 and 10.5 match) and
/// currency (upper-cased). Excluded on purpose: the free-text description, which does not
/// move money and is often regenerated by clients on retry, and anything time-based.
/// </remarks>
public static class RequestFingerprints
{
    private const string Version = "v1";

    public static string For(DepositFundsCommand command) =>
        Compute("deposit", Id(command.AccountId), Amount(command.Amount), Currency(command.Currency));

    public static string For(WithdrawFundsCommand command) =>
        Compute("withdrawal", Id(command.AccountId), Amount(command.Amount), Currency(command.Currency));

    public static string For(TransferFundsCommand command) =>
        Compute(
            "transfer",
            Id(command.SourceAccountId),
            Id(command.DestinationAccountId),
            Amount(command.Amount),
            Currency(command.Currency));

    private static string Compute(string operation, params string[] fields)
    {
        // Newline-separated with a version prefix: unambiguous (no field contains '\n') and
        // lets the canonical form evolve without silently matching old fingerprints.
        var canonical = string.Join('\n', [Version, operation, .. fields]);
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(canonical));
        return Convert.ToHexStringLower(hash);
    }

    private static string Id(Guid id) => id.ToString("D", CultureInfo.InvariantCulture);

    // "G29" drops trailing zeros, so 10.50m and 10.5m share a fingerprint.
    private static string Amount(decimal amount) => amount.ToString("G29", CultureInfo.InvariantCulture);

    private static string Currency(string currency) => currency.Trim().ToUpperInvariant();
}
